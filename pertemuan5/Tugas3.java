package pertemuan5;

public class Tugas3 {
    public static void main(String[] args) {
        int a = 0;
        for(int i = 0; i < 5; i++){
            for(int j = 0; j <= i; j++){
                a++;
                System.out.print(a + " ");
            }
            System.out.println("");
        }
    }
}
