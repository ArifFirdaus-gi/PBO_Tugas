package pertemuan5;

public class Tugas7 {
    public static void main(String[] args) {
        System.out.println("i = 0, i < 10 (++i):");
        int i = 0;
        while(i < 10){
            
            System.out.println(++i);
        }
        System.out.println("");
        
        i = 0;
        System.out.println("i = 0, i < 10 (i++):");
        while(i < 10){
            System.out.println(i++);
        }
    }
}
